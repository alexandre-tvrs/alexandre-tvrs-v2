import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url)),read=name=>fs.readFileSync(path.join(root,name),'utf8');
// A quiet portrait uses the exact geometry and palette of the flying dragon.
const artContext={};vm.createContext(artContext);vm.runInContext(read('dragon.js'),artContext);
const dragon=Object.create(artContext.DragonStudy.prototype);
Object.assign(dragon,{scale:1,cw:7,ch:8,cols:72,rows:54,time:.12,heading:0,facing:1,reaction:'roaming'});
dragon.grid=new Uint8Array(dragon.cols*dragon.rows);dragon.letters=new Uint8Array(dragon.grid.length);
dragon.nodes=Array.from({length:29},(_,i)=>({x:370-i*11,y:300+(i>15?Math.sin((i-15)/13*Math.PI)*25:0)}));
dragon.wing(true);dragon.legs(true);dragon.body();dragon.wing(false);dragon.legs(false);dragon.headArt();
let minX=72,minY=54,maxX=0,maxY=0;
dragon.grid.forEach((p,i)=>{if(p){const x=i%72,y=Math.floor(i/72);minX=Math.min(minX,x);maxX=Math.max(maxX,x);minY=Math.min(minY,y);maxY=Math.max(maxY,y)}});
const paint=[' ',';',':','+','*','#','=',':','/','.',':','+','/',' ','@','*',':'];
let portrait='<pre class="dragon-portrait" aria-hidden="true">';
for(let y=minY;y<=maxY;y++){for(let x=minX;x<=maxX;x++){const i=y*72+x,p=dragon.grid[i],char=dragon.letters[i]?String.fromCharCode(dragon.letters[i]):paint[p]||' ';portrait+='<span class="dragon-cell'+(p?' p'+p:'')+'">'+char+'</span>'}if(y<maxY)portrait+='\n'}
portrait+='</pre>';
fs.writeFileSync(path.join(root,'dragon-portrait.js'),'window.DRAGON_PORTRAIT='+JSON.stringify(portrait)+';\n');
const icon=Object.create(artContext.DragonStudy.prototype);
Object.assign(icon,{scale:1,cw:6,ch:6,cols:22,rows:22,time:0,heading:0,facing:1,reaction:'roaming',nodes:[{x:49,y:81}]});
icon.grid=new Uint8Array(22*22);icon.letters=new Uint8Array(icon.grid.length);icon.headArt();
const colors={3:'#a13f4a',4:'#db7871',5:'#d3a397',6:'#efd2ae',8:'#dcaa79',13:'#210e18',14:'#fff0cd'};
let favicon='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 132 132"><rect width="132" height="132" rx="26" fill="#160f15"/><g shape-rendering="crispEdges">';
icon.grid.forEach((p,i)=>{if(p)favicon+='<rect x="'+i%22*6+'" y="'+Math.floor(i/22)*6+'" width="6" height="6" fill="'+colors[p]+'"/>'});
favicon+='</g></svg>';fs.writeFileSync(path.join(root,'favicon.svg'),favicon);
const blocks={},context={window:{},document:{getElementById:id=>blocks[id]||(blocks[id]={innerHTML:''})}};
vm.createContext(context);vm.runInContext(read('content.js'),context);
vm.runInContext(read('dragon-portrait.js'),context);
vm.runInContext(read('portfolio.js').split('// Native anchors')[0]+'})();',context);
let html=read('layout.html');
for(const[id,block]of Object.entries(blocks))html=html.replace(new RegExp('(<(?:div|ol)[^>]*id="'+id+'"[^>]*>)(</(?:div|ol)>)'),(_,open,close)=>open+block.innerHTML+close);
fs.writeFileSync(path.join(root,'index.html'),html);
html=html.replace('href="favicon.svg"','href="data:image/svg+xml,'+encodeURIComponent(favicon)+'"');
for(const name of ['fonts.css','study.css','village.css','portfolio.css'])html=html.replace('<link rel="stylesheet" href="'+name+'">','<style>'+read(name)+'</style>');
for(const name of ['content.js','dragon-portrait.js','portfolio.js','dragon.js','village.js'])html=html.replace('<script src="'+name+'"></script>','<script>'+read(name)+'</script>');
html=html.replace(/url\((fonts\/[^)]+\.ttf)\)/g,(_,file)=>'url(data:font/ttf;base64,'+fs.readFileSync(path.join(root,file)).toString('base64')+')');
fs.writeFileSync(path.join(root,'abrir-portfolio.html'),html);
console.log('Generated index.html and abrir-portfolio.html with all portfolio content.');
